"""Run every query in sql/04_analysis_queries.sql and write the results to Markdown.

    python -m src.run_analysis                 # writes docs/sample_query_results.md
    python -m src.run_analysis --out other.md

Queries are read-only; the database is never modified.
"""
from __future__ import annotations

import argparse
import logging
import re
import sys
from dataclasses import dataclass
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

from . import config, load

log = logging.getLogger("analysis")

_NAME = re.compile(r"^--\s*name:\s*(\S+)\s*$")
_QUESTION = re.compile(r"^--\s*question:\s*(.+?)\s*$")
_NOTE = re.compile(r"^--\s*note:\s*(.+?)\s*$")


@dataclass
class Query:
    name: str
    question: str
    note: str
    sql: str


def parse_queries(text: str) -> list:
    """Split the SQL file into named queries. Text before the first '-- name:' is ignored."""
    queries, current = [], None
    for line in text.splitlines():
        m = _NAME.match(line)
        if m:
            if current:
                queries.append(current)
            current = {"name": m.group(1), "question": "", "note": "", "lines": []}
            continue
        if current is None:
            continue
        q, n = _QUESTION.match(line), _NOTE.match(line)
        if q:
            current["question"] = q.group(1)
        elif n:
            current["note"] = n.group(1)
        elif not line.strip().startswith("--"):
            current["lines"].append(line)
    if current:
        queries.append(current)
    return [Query(c["name"], c["question"], c["note"], "\n".join(c["lines"]).strip()) for c in queries]


def _fmt(value) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, Decimal):
        return f"{value:f}"
    if isinstance(value, (datetime, date)):
        return str(value)
    return str(value)


def to_markdown_table(columns: list, rows: list) -> str:
    head = "| " + " | ".join(columns) + " |"
    sep = "| " + " | ".join("---" for _ in columns) + " |"
    body = ["| " + " | ".join(_fmt(v).replace("|", "\\|") for v in row) + " |" for row in rows]
    return "\n".join([head, sep, *body])


def run_queries(db_params: dict, queries: list) -> list:
    """Execute queries on a read-only connection. Returns [(Query, columns, rows)]."""
    conn = load.connect(db_params)
    try:
        conn.set_session(readonly=True)
        out = []
        with conn.cursor() as cur:
            for q in queries:
                cur.execute(q.sql)
                cols = [d[0] for d in cur.description]
                out.append((q, cols, cur.fetchall()))
                log.info("%-45s %3d row(s)", q.name, len(out[-1][2]))
        return out
    finally:
        conn.close()


def render_markdown(results: list) -> str:
    parts = [
        "# Sample query results",
        "",
        "Generated by `python -m src.run_analysis` from `sql/04_analysis_queries.sql` "
        "against the loaded PostgreSQL database. Re-run it to refresh these numbers. "
        "Interpretation lives in [analysis_findings.md](analysis_findings.md).",
        "",
    ]
    for q, cols, rows in results:
        parts += [f"## {q.name}", "", f"**Question:** {q.question}", ""]
        if q.note:
            parts += [f"*Note: {q.note}*", ""]
        parts += [to_markdown_table(cols, rows), ""]
    return "\n".join(parts)


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the analytical SQL queries")
    parser.add_argument("--out", type=Path, default=config.DOCS_DIR / "sample_query_results.md")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)-7s %(message)s",
                        datefmt="%Y-%m-%d %H:%M:%S", stream=sys.stdout)
    try:
        queries = parse_queries((config.SQL_DIR / "04_analysis_queries.sql").read_text(encoding="utf-8"))
        results = run_queries(config.get_db_params(), queries)
    except Exception as exc:  # noqa: BLE001
        log.error("Analysis failed: %s", exc)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render_markdown(results), encoding="utf-8")
    log.info("Wrote %d query results to %s", len(results), args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
